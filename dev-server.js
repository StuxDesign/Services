#!/usr/bin/env node
// Stux.Design Services — local static dev server.
//
// Serves the repo root as-is, except for one route: /assets/js/dev-mode.js
// is generated on the fly instead of read from disk, so DEV_MODE can be
// forced on for local runs without ever touching (or risking a commit of)
// the real, gitignored-free, always-`false` file in assets/js/dev-mode.js.
//
// Usage: node dev-server.js [port] [--no-dev-mode] [--lan]
//   --lan  listen on all interfaces (0.0.0.0) instead of 127.0.0.1 only, so phones and
//          tablets on your network can open it; prints this machine's addresses to use.
const http = require("http");
const fs = require("fs");
const path = require("path");
const os = require("os");

const ROOT = __dirname;
const args = process.argv.slice(2);
let port = 8080;
let devMode = true;
let host = "127.0.0.1";

for (const arg of args) {
  if (arg === "--no-dev-mode") {
    devMode = false;
  } else if (arg === "--lan") {
    host = "0.0.0.0";
  } else if (/^\d+$/.test(arg)) {
    port = parseInt(arg, 10);
  } else {
    console.error(`Unknown option: ${arg}`);
    console.error("Usage: node dev-server.js [port] [--no-dev-mode] [--lan]");
    process.exit(1);
  }
}

const MIME = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".ico": "image/x-icon",
  ".webmanifest": "application/manifest+json; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".txt": "text/plain; charset=utf-8",
  ".md": "text/markdown; charset=utf-8",
};

const server = http.createServer((req, res) => {
  const urlPath = decodeURIComponent(req.url.split("?")[0]);

  if (urlPath === "/assets/js/dev-mode.js") {
    res.writeHead(200, { "Content-Type": MIME[".js"] });
    res.end(`// Generated by dev-server.js for this run.\nwindow.DEV_MODE = ${devMode};\n`);
    return;
  }

  let filePath = path.join(ROOT, urlPath);

  // Directory / pretty-URL fallback: /legal/privacy/ -> /legal/privacy/index.html
  const tryPaths = [filePath];
  if (urlPath.endsWith("/")) {
    tryPaths.push(path.join(filePath, "index.html"));
  } else {
    tryPaths.push(path.join(filePath, "index.html"));
    tryPaths.push(`${filePath}.html`);
  }

  const found = tryPaths.find((p) => {
    try {
      return fs.statSync(p).isFile();
    } catch {
      return false;
    }
  });

  if (!found) {
    res.writeHead(404, { "Content-Type": MIME[".html"] });
    res.end("<h1>404 — Not found</h1>");
    return;
  }

  const ext = path.extname(found);
  res.writeHead(200, { "Content-Type": MIME[ext] || "application/octet-stream" });
  fs.createReadStream(found).pipe(res);
});

server.listen(port, host, () => {
  console.log(`Stux.Design Services running at http://127.0.0.1:${port}`);
  if (host === "0.0.0.0") {
    // This machine's IPv4 addresses, minus loopback
    const addrs = Object.values(os.networkInterfaces())
      .flat()
      .filter((i) => i && (i.family === "IPv4" || i.family === 4) && !i.internal)
      .map((i) => i.address);
    console.log("On your local network (--lan), open one of these on the other device:");
    for (const a of addrs) console.log(`    http://${a}:${port}`);
    console.log("  (usually the 192.168.x.x one; allow Node through the firewall if asked)");
  }
  if (devMode) {
    console.log("DEV_MODE forced on for this run (banner shows) — pass --no-dev-mode to disable.");
  } else {
    console.log("DEV_MODE forced off for this run — behaving like production.");
  }
});
